# ---------------------------------------------------------------- 動態觀察池
# 這幾行必須放在檔案最後：上面的參數都定義完了才組 UNIVERSE。
# 讀 data/universe_current.json（由 src/universe_live.py 每月重排產生）。
# 刻意不 import universe_live——那會造成循環 import，而且 config 被大量模組
# 匯入，不該在 import 時去讀十年的成交值檔。
def _load_universe():
    import json as _json
    import os as _os
    p = _os.path.join(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))),
                      "data", "universe_current.json")
    try:
        with open(p, encoding="utf-8") as f:
            d = _json.load(f)
        u = d.get("universe") or {}
        if len(u) >= 50:                      # 太少一定是壞了，寧可用 fallback
            return {str(k): str(v) for k, v in u.items()}, d.get("as_of")
    except Exception:
        pass
    return dict(FALLBACK_UNIVERSE), None


UNIVERSE, UNIVERSE_AS_OF = _load_universe()
UNIVERSE_IS_FALLBACK = UNIVERSE_AS_OF is None


def refresh_universe():
    """重排之後在同一個 process 裡重新讀池子。

    config 通常在程式一開始就被 import，UNIVERSE 那時就綁定好了。
    daily_update 是先重排再抓價，如果不重讀，當天抓的還會是舊名單。
    """
    global UNIVERSE, UNIVERSE_AS_OF, UNIVERSE_IS_FALLBACK
    UNIVERSE, UNIVERSE_AS_OF = _load_universe()
    UNIVERSE_IS_FALLBACK = UNIVERSE_AS_OF is None
    return UNIVERSE
